#!/usr/bin/env python3
"""Generate docs/data/data-dictionary.md from the tool catalogs, contract schemas, example config and code limits.

Sources: schemas/*-tools.json (tool names, parameters and results), contracts/*.schema.json (record fields),
cstack.config.example.json (configuration keys) and numeric limit constants in the adapters, core, CLI and tools.

  python3 -B tools/gen_data_dictionary.py           # rewrite the dictionary
  python3 -B tools/gen_data_dictionary.py --check   # exit 1 if the committed dictionary differs from the sources
"""
import argparse, ast, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs/data/data-dictionary.md'
LIMIT_FILES = ('adapters/*.py', 'adapters/memory/*.py', 'poodo_core/*.py', 'cli.py', 'bootstrap.py', 'tools/*.py')
LIMIT = re.compile(r'^(_?(?:[A-Z0-9]+_)*[A-Z0-9]*(?:MAX|LIMIT|TIMEOUT|BUDGET|BYTES|FRAME|CAP)[A-Z0-9_]*) = ([0-9_ *+()]+)$')
BASELINE = '6ae5481fd302439dabb23044d1b715ac8c4a9bec'

HEADER = f"""# Cstack data dictionary

| Field | Value |
|---|---|
| Document ID | CSTACK-DD |
| Version | 1.0 |
| Status | Baselined (generated) |
| Owner | Akilleez-QA |
| Date | 2026-11-08 |
| Baseline commit | {BASELINE} |
| Applies to | cstack main at baseline commit |
| Classification | Self-assessed Class E analog; not safety-critical (see [SMP §1](../plan/software-management-plan.md#1-software-classification-self-assessed)) |

> Organized after [NPR 7150.2D](https://nodis3.gsfc.nasa.gov/displayAll.cfm?Internal_ID=N_PR_7150_002D_&page_name=all), [NASA-STD-8739.8B](https://standards.nasa.gov/standard/nasa/nasa-std-87398) and the [NASA Software Engineering Handbook](https://swehb.nasa.gov/display/SWEHBVD/7.18+-+Documentation+Guidance) documentation guidance. This is not a NASA compliance determination or certification. The software classification is a self-assessed analog (Class E, not safety-critical); no NASA authority, independent verification and validation, or hazard analysis is asserted. The document describes the implementation inspected at the baseline commit.

Generated by `python3 -B tools/gen_data_dictionary.py`; `--check` (run by `tests/test_data_dictionary.py`) fails when this file and its sources disagree. Do not edit by hand.

Not applicable: channelization, rate-group, raw or calibrated sensor, telemetry, data-recorder and partitioning data. Cstack has no hardware or telemetry interfaces.

Related references: [commands](../guides/reference/commands.md), [configuration](../guides/reference/configuration.md) and [environment variables](../guides/reference/environment.md). Foundation reference data (saturation tables, exposure limits, kinematics) is defined and sourced in each vendored Foundation's own documentation under `foundations/`; Cstack passes it through unchanged.
"""


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ').strip()


def first_sentence(text):
    text = (text or '').strip()
    m = re.match(r'(.+?\.)(\s|$)', text)
    return m.group(1) if m else text


def describe(schema):
    if not isinstance(schema, dict):
        return ''
    if 'const' in schema:
        return f"const {json.dumps(schema['const'])}"
    if 'enum' in schema:
        return 'one of ' + ', '.join(json.dumps(v) for v in schema['enum'])
    for key in ('oneOf', 'anyOf'):
        if key in schema:
            return ' or '.join(filter(None, (describe(s) for s in schema[key])))
    kind = schema.get('type', '')
    kind = '/'.join(kind) if isinstance(kind, list) else kind
    if '$ref' in schema and not kind:
        kind = schema['$ref'].rsplit('/', 1)[-1]
    bits = [kind] if kind else []
    for key, label in (('minimum', 'min'), ('maximum', 'max'), ('exclusiveMinimum', '>'), ('exclusiveMaximum', '<'),
                       ('minLength', 'min length'), ('maxLength', 'max length'), ('minItems', 'min items'),
                       ('maxItems', 'max items'), ('pattern', 'pattern')):
        if key in schema:
            bits.append(f'{label} {schema[key]}')
    if kind == 'array' and isinstance(schema.get('items'), dict):
        inner = describe(schema['items'])
        if inner:
            bits.append(f'of {inner}')
    return ', '.join(bits)


def fields(schema):
    props = schema.get('properties', {}) if isinstance(schema, dict) else {}
    required = set(schema.get('required', [])) if isinstance(schema, dict) else set()
    return [(name, describe(s), name in required, first_sentence(s.get('description', '')) if isinstance(s, dict) else '')
            for name, s in props.items()]


def tools_section():
    out = ['## 1. Tools\n', 'One table per Foundation catalog. Parameters are the top-level input fields; `*` marks required.\n']
    for path in sorted((ROOT / 'schemas').glob('*-tools.json')):
        catalog = json.loads(path.read_text(encoding='utf-8'))
        out.append(f'### `{path.relative_to(ROOT).as_posix()}`\n')
        out.append('| Tool | Purpose | Parameters | Result fields |\n|---|---|---|---|')
        for tool in catalog:
            params = ', '.join(f"`{n}`{'*' if r else ''} ({cell(d) or 'any'})" for n, d, r, _ in fields(tool.get('inputSchema', {})))
            result = ', '.join(f'`{n}`' for n, _, _, _ in fields(tool.get('outputSchema', {})))
            out.append(f"| `{tool['name']}` | {cell(first_sentence(tool.get('description', '')))} | {cell(params) or 'none'} | {cell(result) or '-'} |")
        out.append('')
    return out


def records_section():
    out = ['## 2. Records\n', 'Fields of each contract schema; `yes` in Required means the schema requires it.\n']
    for path in sorted((ROOT / 'contracts').glob('*.schema.json')):
        schema = json.loads(path.read_text(encoding='utf-8'))
        out.append(f"### {cell(schema.get('title', path.name))} (`{path.relative_to(ROOT).as_posix()}`)\n")
        out.append('| Field | Type and limits | Required | Meaning |\n|---|---|---|---|')
        for name, kind, req, desc in fields(schema):
            out.append(f"| `{name}` | {cell(kind) or 'any'} | {'yes' if req else 'no'} | {cell(desc) or '-'} |")
        out.append('')
    out.append('Ledger, approval and evidence record formats beyond these schemas are specified in the '
               '[EndoForge ICD](../icd/icd-endoforge.md) and [`contracts/INTERFACES.md`](../../contracts/INTERFACES.md).\n')
    return out


def walk(prefix, value):
    if isinstance(value, dict):
        for k, v in value.items():
            yield from walk(f'{prefix}.{k}' if prefix else k, v)
    else:
        yield prefix, value


def config_section():
    example = json.loads((ROOT / 'cstack.config.example.json').read_text(encoding='utf-8'))
    out = ['## 3. Configuration keys\n',
           'Keys in `cstack.config.example.json`, with the example value. Meanings and defaults are in the '
           '[configuration reference](../guides/reference/configuration.md).\n',
           '| Key | Type | Example value |\n|---|---|---|']
    for key, value in walk('', example):
        kind = type(value).__name__.replace('str', 'string').replace('int', 'integer').replace('list', 'array')
        out.append(f'| `{key}` | {kind} | `{cell(json.dumps(value))}` |')
    out.append('')
    return out


def evaluate(expr):
    node = ast.parse(expr.replace('_', ''), mode='eval').body
    def ev(n):
        if isinstance(n, ast.Constant) and isinstance(n.value, int):
            return n.value
        if isinstance(n, ast.BinOp) and isinstance(n.op, (ast.Mult, ast.Pow, ast.Add)):
            a, b = ev(n.left), ev(n.right)
            return a * b if isinstance(n.op, ast.Mult) else a ** b if isinstance(n.op, ast.Pow) else a + b
        raise ValueError(expr)
    return ev(node)


def limits_section():
    out = ['## 4. Operational limits\n', 'Module-level numeric limits found in the code. Names state the quantity; '
           'bytes unless the name says otherwise.\n', '| Limit | Value | Defined in |\n|---|---|---|']
    seen = set()
    for pattern in LIMIT_FILES:
        for path in sorted(ROOT.glob(pattern)):
            for n, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
                m = LIMIT.match(line)
                if m and (path, m.group(1)) not in seen:
                    seen.add((path, m.group(1)))
                    try:
                        value = evaluate(m.group(2).strip())
                    except (ValueError, SyntaxError):
                        continue
                    out.append(f'| `{m.group(1)}` | {value:,} | `{path.relative_to(ROOT).as_posix()}` |')
    out.append('')
    return out


def render():
    lines = [HEADER] + tools_section() + records_section() + config_section() + limits_section()
    lines.append('## Change history\n')
    lines.append('| Version | Date | Commit | Change | Reviewed in |\n|---|---|---|---|---|')
    lines.append(f'| 1.0 | 2026-11-08 | {BASELINE} | Initial generated baseline | docs/nasa-standard PR |')
    return '\n'.join(lines) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        current = OUT.read_text(encoding='utf-8') if OUT.is_file() else ''
        if current != text:
            print(f'{OUT.relative_to(ROOT)} is stale; run python3 -B tools/gen_data_dictionary.py', file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding='utf-8')
    print(OUT.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
